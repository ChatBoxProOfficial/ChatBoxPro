import { chromium, devices } from 'playwright'
const b = await chromium.launch({ channel: 'msedge', headless: true })
const c = await b.newContext({ ...devices['Pixel 7'], permissions: ['microphone'] })
const p = await c.newPage()
const errors = []
p.on('pageerror', (e) => errors.push(e.message))
await p.goto('http://127.0.0.1:8852/', { waitUntil: 'networkidle' })
await p.waitForSelector('.onboarding', { timeout: 15000 })
await p.fill('.onboarding .field input', '测试')
await p.getByRole('button', { name: '开始使用' }).click()
await p.waitForTimeout(600)
console.log('1) 总调试胶囊:', await p.locator('.debug-pill').innerText())
console.log('2) 加号按钮:', await p.locator('.tool-btn.round').first().count())
console.log('3) 麦克风按钮:', await p.locator('.mic').count())
await p.locator('.debug-pill').click()
await p.waitForTimeout(400)
console.log('4) 调试面板打开:', await p.locator('.model-pop').count())
await p.screenshot({ path: 'shots/154-composer-redesign.png' })
// 桌面端视图
const c2 = await b.newContext({ viewport: { width: 1200, height: 800 }, colorScheme: 'light' })
const p2 = await c2.newPage()
await p2.goto('http://127.0.0.1:8852/', { waitUntil: 'networkidle' })
await p2.waitForSelector('.onboarding', { timeout: 15000 })
await p2.fill('.onboarding .field input', '桌面')
await p2.getByRole('button', { name: '开始使用' }).click()
await p2.waitForTimeout(600)
await p2.screenshot({ path: 'shots/155-composer-desktop.png' })
console.log('控制台错误:', errors.length)
await b.close()

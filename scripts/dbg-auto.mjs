import { chromium } from 'playwright'
const b = await chromium.launch({ channel: 'msedge', headless: true })
const c = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
const p = await c.newPage()
p.on('pageerror', (e) => console.log('PAGEERROR:', e.message))
await p.goto('http://127.0.0.1:8816/', { waitUntil: 'networkidle' })
await p.waitForSelector('.composer', { timeout: 15000 })
// key
await p.getByRole('button', { name: '展开栏目' }).click()
await p.waitForTimeout(400)
await p.locator('.drawer-foot').click()
await p.waitForSelector('.settings-dialog', { timeout: 8000 })
await p.getByRole('button', { name: 'ChatBox Pro 账号与模型', exact: true }).click()
await p.waitForSelector('input[type=password]', { timeout: 5000 })
await p.fill('input[type=password]', 'sk-mock-key')
await p.getByRole('button', { name: '保存', exact: true }).click()
await p.waitForTimeout(400)
await p.locator('.settings-close').click()
// 打开自动压缩（阈值调到极低，便于触发）
await p.evaluate(async () => {
  const db = await new Promise((res) => { const r = indexedDB.open('chatbox-pro', 1); r.onupgradeneeded = () => { const d = r.result; if (!d.objectStoreNames.contains('kv')) d.createObjectStore('kv') }; r.onsuccess = () => res(r.result) })
  await new Promise((res) => { const t = db.transaction('kv', 'readwrite'); t.objectStore('kv').put({ autoCompact: true, compactThreshold: 0.005 }, 'settings'); t.oncomplete = () => res() })
})
await p.reload({ waitUntil: 'networkidle' })
await p.waitForSelector('.composer', { timeout: 15000 })
await p.fill('.composer-input', '天空为什么是蓝色？')
await p.getByRole('button', { name: '发送' }).click()
await p.waitForSelector('.msg.assistant .md', { timeout: 20000 })
await p.waitForSelector('.msg.summary', { timeout: 20000 })
const summary = await p.locator('.summary-body').innerText()
console.log('✓ 自动压缩已触发，摘要:', summary.slice(0, 30))
await p.screenshot({ path: 'shots/78-auto-compact-fired.png' })
await b.close()

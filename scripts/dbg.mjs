import { chromium } from 'playwright'
const b = await chromium.launch({ channel: 'msedge', headless: true })
const c = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
const p = await c.newPage()
p.on('console', (m) => { if (m.text().includes('error')) console.log('console:', m.text()) })
await p.goto('http://127.0.0.1:8812/', { waitUntil: 'networkidle' })
await p.waitForSelector('.composer', { timeout: 15000 })
await p.locator('.model-chip').click()
await p.waitForSelector('.team-row', { timeout: 5000 })
const rows = p.locator('.team-row')
console.log('开关行数:', await rows.count())
for (let i = 0; i < await rows.count(); i++) console.log(i, (await rows.nth(i).innerText()).split('\n')[0])
const row = rows.filter({ hasText: '本地工具' })
console.log('找到本地工具行:', await row.count())
const sw = row.locator('.switch')
console.log('点击前 class:', await sw.getAttribute('class'))
await sw.click()
await p.waitForTimeout(500)
console.log('点击后 class:', await sw.getAttribute('class'))
await p.screenshot({ path: 'shots/dbg-popover.png' })
await b.close()

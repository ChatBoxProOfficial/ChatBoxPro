import { chromium } from 'playwright'
const b = await chromium.launch({ channel: 'msedge', headless: true })
const c = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
const p = await c.newPage()
p.on('pageerror', (e) => console.log('PAGEERROR:', e.message))
await p.goto('http://127.0.0.1:8812/', { waitUntil: 'networkidle' })
await p.waitForSelector('.composer', { timeout: 15000 })
await p.locator('.model-chip').click()
await p.waitForSelector('.team-row', { timeout: 5000 })
const row = p.locator('.team-row').filter({ hasText: '本地工具' })
await row.locator('.switch').click()
await p.waitForTimeout(300)
console.log('checked:', await row.locator('input[role=switch]').isChecked())
await p.keyboard.press('Escape')
await p.waitForTimeout(400)
console.log('mask 数量:', await p.locator('.pop-mask').count())
await p.fill('.composer-input', '现在几点了？')
await p.getByRole('button', { name: '发送' }).click()
await p.waitForTimeout(5000)
console.log('tool 消息数:', await p.locator('.msg.tool').count())
console.log('assistant 数:', await p.locator('.msg.assistant').count())
await p.screenshot({ path: 'shots/dbg-tool2.png' })
await b.close()
